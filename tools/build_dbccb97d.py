#!/usr/bin/env python3
"""Session `dbccb97d` — render the dated-capture dashboard from the CSVs.

Pages (static, self-contained, no JavaScript, no framework):
  dbccb97d/index.html           landing: headline findings, census, links
  dbccb97d/venues.html          the 13 Week 11 venues from the official game centres
  dbccb97d/hub-delta.html       the 347-row hub read of 2026-11-16T18:05Z + delta summary
  dbccb97d/reverification.html  the 9 verification checks
  dbccb97d/flagged.html         this session's flag (FL-129) and the venue-naming flag it evidences (FL-118), plus the open flags it references

Every table row carries its official source link. Blank official cells render as
"not published" — never zero, never a guess. Deterministic: running twice writes
the same bytes.
"""
import csv
import html
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
OUT = ROOT / "dbccb97d"
ASSETS = OUT / "assets"

CSS = """/* session dbccb97d dashboard — clean, table-first, no framework */
* { box-sizing: border-box; }
body { margin: 0; font: 15px/1.55 -apple-system, "Segoe UI", Roboto, Helvetica, Arial, sans-serif;
       color: #1c2430; background: #f5f7fa; }
header { background: #10233f; color: #fff; padding: 22px 28px; }
header h1 { margin: 0 0 4px; font-size: 22px; }
header p { margin: 0; color: #b9c8dc; font-size: 13px; }
nav { background: #10233f; padding: 0 28px 14px; }
nav a { color: #9fc1e8; margin-right: 16px; text-decoration: none; font-size: 14px; }
nav a:hover { color: #fff; }
main { max-width: 1180px; margin: 24px auto 60px; padding: 0 20px; }
h2 { font-size: 19px; margin: 30px 0 10px; }
h3 { font-size: 16px; margin: 22px 0 8px; }
p.lede { font-size: 15px; color: #33415a; }
.cards { display: flex; flex-wrap: wrap; gap: 14px; margin: 16px 0; }
.card { background: #fff; border: 1px solid #dde4ee; border-radius: 10px;
        padding: 14px 18px; min-width: 180px; flex: 1; }
.card .n { font-size: 26px; font-weight: 700; color: #10233f; }
.card .l { font-size: 12px; color: #5a6b85; text-transform: uppercase; letter-spacing: .04em; }
table { border-collapse: collapse; width: 100%; background: #fff; margin: 12px 0 22px;
        font-size: 13.5px; }
th, td { border: 1px solid #dde4ee; padding: 6px 9px; text-align: left; vertical-align: top; }
th { background: #eef2f8; font-size: 12px; text-transform: uppercase; letter-spacing: .03em;
     color: #41536e; }
tr:nth-child(even) td { background: #fafbfd; }
td a { color: #14538c; }
.tag { display: inline-block; padding: 1px 8px; border-radius: 999px; font-size: 11.5px;
       font-weight: 600; }
.match { background: #e3f4e8; color: #1c6b3a; }
.mismatch { background: #fdeaea; color: #9c2b2b; }
.partial { background: #fdf3e0; color: #8a5a12; }
.finding { background: #e8f0fd; color: #14538c; }
.scroll { max-height: 560px; overflow: auto; border: 1px solid #dde4ee; border-radius: 8px; }
.note { background: #fff; border-left: 4px solid #14538c; padding: 10px 14px;
        margin: 14px 0; font-size: 13.5px; color: #33415a; }
footer { color: #71809a; font-size: 12px; padding: 0 28px 30px; }
"""

NAV = [("index.html", "Landing"), ("venues.html", "Week 11 venues"),
       ("hub-delta.html", "Hub read & delta"),
       ("reverification.html", "Verification"), ("flagged.html", "Flagged")]


def esc(s):
    return html.escape(s, quote=True)


def read_csv(path):
    with path.open(encoding="utf-8", newline="") as f:
        rows = list(csv.reader(f, delimiter="|"))
    return rows[0], rows[1:]


def page(title, body):
    nav = "".join(f'<a href="{u}">{esc(t)}</a>' for u, t in NAV)
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{esc(title)} — NFL2 · session dbccb97d</title>
<link rel="stylesheet" href="assets/style.css">
</head>
<body>
<header>
  <h1>NFL2 — official-source verification, session `dbccb97d`</h1>
  <p>Dated captures of 2026-11-16 (18:05Z–18:12Z) from nfl.com · every row sourced ·
     blanks render as “not published”</p>
</header>
<nav>{nav}</nav>
<main>
{body}
</main>
<footer>Generated by tools/build_dbccb97d.py from data/hub_read_dbccb97d_20261116.csv,
data/venues_week11_dbccb97d_20261116.csv and data/reverification_dbccb97d.csv ·
verified by tools/verify_dbccb97d.py (28 checks).</footer>
</body>
</html>"""


def main():
    OUT.mkdir(exist_ok=True)
    ASSETS.mkdir(exist_ok=True)
    (ASSETS / "style.css").write_text(CSS, encoding="utf-8")

    hub_header, hub_rows = read_csv(DATA / "hub_read_dbccb97d_20261116.csv")
    vend_header, vend_rows = read_csv(DATA / "venues_week11_dbccb97d_20261116.csv")
    rev_header, rev_rows = read_csv(DATA / "reverification_dbccb97d.csv")

    # ---------------- index ----------------
    cards = [
        ("347", "hub rows · 28 clubs"),
        ("0", "cell drift vs both prior registers"),
        ("13", "Week 11 venues from game centres"),
        ("3", "venue-naming discrepancies (FL-118)"),
        ("28", "verifier checks, all passing"),
    ]
    card_html = "".join(
        f'<div class="card"><div class="n">{esc(n)}</div>'
        f'<div class="l">{esc(l)}</div></div>' for n, l in cards)
    index_body = f"""
<p class="lede">This session took the sixth dated read of the official Week 10 injury hub
(2026-11-16T18:05Z, all eight page chunks, 347 rows across 28 clubs), re-verified it cell
by cell against the two newest registers in the repository, transcribed the venue of every
Week 11 fixture from its own official game centre, and re-checked the Week 11 slate, the
bye list and the schedule-release article against the league's own pages.</p>
<div class="cards">{card_html}</div>
<h2>Headline findings</h2>
<div class="note"><strong>The hub is stable.</strong> Against the 15:07Z register and the
14:44Z register the 18:05Z read agrees on all 347 shared keys — zero mismatched, zero new,
zero missing cells. Three keys match under a name variant only (the hub's printed display
name against the player-page form an earlier register used): Chig/Chigoziem Okonkwo (WAS),
Jacob/Jake Hummel (HOU), Kam/Kamren Curl (LAR).</div>
<div class="note"><strong>Venue capture resolves FL-112 with an official source.</strong>
The schedule page prints no stadium names; its hotel-link parameters carry three names
that differ from the official game centres (FL-118): NRG Stadium vs RELIANT STADIUM
(W11-01), GEHA Field at Arrowhead Stadium vs ARROWHEAD STADIUM (W11-07), FedEx Field vs
NORTHWEST STADIUM (W11-13). The game-centre values are published on the venues page.</div>
<div class="note"><strong>The misplacement family persists.</strong> All eight
player/block sightings of the FL-113 family were present at 18:05Z, including one new
sighting — Kyler Murray printed in the Vikings block (FL-129). The hub's club column
stores the block as printed and must never be used as a join key.</div>
<div class="note"><strong>The schedule-release article's own date stamp is still not
rendered in the fetched content</strong> (FL-111): its related-content block dates three
sibling schedule-release articles 2026-05-15, so the window narrows but the date cell
stays blank under the blank policy.</div>
<h2>Pages</h2>
<table>
<tr><th>Page</th><th>What it holds</th><th>Source</th></tr>
<tr><td><a href="venues.html">Week 11 venues</a></td>
    <td>The venue of each of the 13 Week 11 fixtures, transcribed from its own official game centre</td>
    <td><a href="https://www.nfl.com/games/colts-at-texans-2026-reg-11">nfl.com game centres</a></td></tr>
<tr><td><a href="hub-delta.html">Hub read &amp; delta</a></td>
    <td>The full 347-row hub read of 2026-11-16T18:05Z and the delta summary against the two prior registers</td>
    <td><a href="https://www.nfl.com/injuries/">NFL injury hub</a></td></tr>
<tr><td><a href="reverification.html">Verification</a></td>
    <td>The nine verification checks (census, row-level deltas, slate, bye list, venue naming, FL-111)</td>
    <td><a href="https://www.nfl.com/schedules/2026/by-week/week-11">Week 11 schedule</a>,
        <a href="https://www.nfl.com/injuries/">injury hub</a></td></tr>
<tr><td><a href="flagged.html">Flagged</a></td>
    <td>FL-129 as published, and FL-118 which it evidences, plus the open flags this session references</td>
    <td><a href="https://www.nfl.com/injuries/">NFL injury hub</a>,
        <a href="https://www.nfl.com/games/cardinals-at-chiefs-2026-reg-11">game centres</a></td></tr>
</table>
"""
    (OUT / "index.html").write_text(page("Landing", index_body), encoding="utf-8")

    # ---------------- venues ----------------
    rows_html = []
    for r in vend_rows:
        gid, away, home, slug, loc, stad, read_utc, url = r
        rows_html.append(
            f"<tr><td>{esc(gid)}</td><td>{esc(away)}</td><td>{esc(home)}</td>"
            f"<td>{esc(loc)}</td><td>{esc(stad)}</td>"
            f'<td><a href="{esc(url)}">{esc(url)}</a></td>'
            f"<td>{esc(read_utc)}</td></tr>")
    venues_body = f"""
<h2>Week 11 venues — transcribed from the official game centres</h2>
<p class="lede">Read 2026-11-16T18:05Z. The official schedule page displays no stadium
names; each fixture's own game centre publishes them under <em>Game Info → Location /
Stadium</em>. These are the values recommended for the site's venue column (FL-118).</p>
<table>
<tr><th>Game</th><th>Away</th><th>Home</th><th>Location (as printed)</th>
<th>Stadium (as printed)</th><th>Official source</th><th>Read</th></tr>
{''.join(rows_html)}
</table>
<div class="note"><strong>Naming discrepancy (FL-118).</strong> Three of the thirteen
fixtures carry a different stadium name on the schedule page's own hotel-link parameters
than on the game centre: W11-01 RELIANT STADIUM vs <em>NRG Stadium</em>; W11-07
ARROWHEAD STADIUM vs <em>GEHA Field at Arrowhead Stadium</em>; W11-13 NORTHWEST STADIUM vs
<em>FedEx Field</em>. The remaining ten agree once case is normalised. The parameter-encoded
names are not adopted anywhere on this site.</div>
<div class="note">Observation, not a gap: every Week 11 game centre prints
“Injury Report is not available at this time” on 2026-11-16 — Week 11 reports are not yet
published (the fixture week begins Thursday 19 November).</div>
"""
    (OUT / "venues.html").write_text(page("Week 11 venues", venues_body), encoding="utf-8")

    # ---------------- hub-delta ----------------
    hub_rows_html = []
    for r in hub_rows:
        read_utc, url, club, player, pos, inj, prac, gs = r
        inj_cell = esc(inj) if inj else "not published"
        gs_cell = esc(gs) if gs else "not published"
        hub_rows_html.append(
            f"<tr><td>{esc(club)}</td><td>{esc(player)}</td><td>{esc(pos)}</td>"
            f"<td>{inj_cell}</td><td>{esc(prac)}</td><td>{gs_cell}</td>"
            f'<td><a href="{esc(url)}">{esc(url)}</a></td></tr>')
    hub_body = f"""
<h2>Official Week 10 injury hub — read 2026-11-16T18:05Z</h2>
<p class="lede">All eight page chunks, 347 rows across the 28 clubs on the slate. Practice
codes: F = Full, L = Limited, D = Did Not Participate. Cells the official page left blank
render as “not published”. The club column stores the hub's club block as printed — three
players are printed under a block other than their own (FL-113/FL-129) and the column must
not be used as a join key.</p>
<div class="scroll"><table>
<tr><th>Club (block as printed)</th><th>Player</th><th>Pos</th><th>Injury</th>
<th>Practice</th><th>Game status</th><th>Source</th></tr>
{''.join(hub_rows_html)}
</table></div>
<h2>Delta against the two newest registers</h2>
<table>
<tr><th>Comparison</th><th>Result</th><th>Detail</th><th>Source</th></tr>
<tr><td>vs data/hub_read_f3ec0ff8_20261116.csv (15:07Z)</td>
    <td><span class="tag match">MATCH</span></td>
    <td>0 mismatched, 0 new, 0 missing on 347 keys; 3 name variants only</td>
    <td><a href="https://www.nfl.com/injuries/">injury hub</a></td></tr>
<tr><td>vs data/injuries_wk10_4e475b8b_20261116.csv (14:44Z)</td>
    <td><span class="tag match">MATCH</span></td>
    <td>0 mismatched, 0 new, 0 missing on 347 keys</td>
    <td><a href="https://www.nfl.com/injuries/">injury hub</a></td></tr>
</table>
"""
    (OUT / "hub-delta.html").write_text(page("Hub read & delta", hub_body), encoding="utf-8")

    # ---------------- reverification ----------------
    tag_class = {"MATCH": "match", "MISMATCH": "mismatch", "PARTIAL": "partial"}
    rev_rows_html = []
    for r in rev_rows:
        rid, check, scope, pub, off, result, note, src = r
        rev_rows_html.append(
            f"<tr><td>{esc(rid)}</td><td>{esc(check)}</td><td>{esc(scope)}</td>"
            f"<td>{esc(pub)}</td><td>{esc(off)}</td>"
            f'<td><span class="tag {tag_class.get(result, "finding")}">{esc(result)}</span></td>'
            f"<td>{esc(note)}</td>"
            f'<td><a href="{esc(src)}">{esc(src)}</a></td></tr>')
    rev_body = f"""
<h2>Verification checks — session dbccb97d</h2>
<p class="lede">Nine checks produced by tools/dbccb97d_capture.py and re-derived by
tools/verify_dbccb97d.py on every run. MATCH rows assert agreement; the MISMATCH row
documents a real disagreement between two official readings (a finding, registered as
FL-118); the PARTIAL row records a blank that stays blank under the blank policy (FL-111).</p>
<table>
<tr><th>ID</th><th>Check</th><th>Scope</th><th>Published value</th>
<th>Official value</th><th>Result</th><th>Note</th><th>Source</th></tr>
{''.join(rev_rows_html)}
</table>
"""
    (OUT / "reverification.html").write_text(page("Verification", rev_body), encoding="utf-8")

    # ---------------- flagged ----------------
    flags_path = DATA / "flags.csv"
    flagged_rows = []
    wanted = {"FL-118", "FL-129", "FL-111", "FL-112", "FL-113", "FL-114"}
    with flags_path.open(encoding="utf-8", newline="") as f:
        for r in csv.DictReader(f, delimiter="|"):
            if r["id"] in wanted:
                srcs = " :: ".join(
                    u for u in r["source"].split(",") if u.startswith("https://"))
                flagged_rows.append(
                    f"<tr><td>{esc(r['id'])}</td><td>{esc(r['type'])}</td>"
                    f"<td>{esc(r['severity'])}</td><td>{esc(r['finding'])}</td>"
                    f"<td>{esc(r['decision_impact'])}</td>"
                    f"<td>{esc(r['status'])}</td>"
                    f'<td><a href="{esc(srcs)}">{esc(srcs)}</a></td></tr>')
    flagged_body = f"""
<h2>Flagged for review — session dbccb97d</h2>
<p class="lede">This session's new flag (FL-129) and plus the open flags it
references. None of them blocks the build or the merge; they are published so the owner can
review the source links and decide.</p>
<table>
<tr><th>ID</th><th>Type</th><th>Severity</th><th>Finding</th>
<th>Decision impact</th><th>Status</th><th>Source</th></tr>
{''.join(sorted(flagged_rows))}
</table>
"""
    (OUT / "flagged.html").write_text(page("Flagged", flagged_body), encoding="utf-8")

    print(f"dbccb97d/: {len(list(OUT.glob('*.html')))} pages built from "
          f"{len(hub_rows)} hub rows, {len(vend_rows)} venues, {len(rev_rows)} checks")
    return 0


if __name__ == "__main__":
    sys.exit(main())
