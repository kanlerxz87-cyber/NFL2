#!/usr/bin/env python3
"""Session 2268bfb2 - verification gate for the s2268/ tree.

scripts/audit_all_pages.py predates this tree and only walks root, analytics/, docs/,
review/, portal/ and site/. Rather than edit another session's auditor, this one applies
the same four assertions to s2268/ and then re-runs every suite already in the repository
so nothing else regressed:

  1. every local href/src resolves to a file that exists
  2. every <tbody><tr> carries at least one link to an approved official domain
  3. header cell counts match body cell counts in every table
  4. the CSVs regenerate byte-identically, so the pages cannot drift from the data

Plus one check the other suites do not make: that this session touched no file outside
its own scope.

Exit code 1 on any failure.
"""

from __future__ import annotations

import hashlib
import html.parser
import os
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "s2268"

OFFICIAL_DOMAINS = {
    "nfl.com", "www.nfl.com", "operations.nfl.com", "static.www.nfl.com",
    "nextgenstats.nfl.com", "github.com", "kanlerxz87-cyber.github.io",
    "www.patriots.com", "www.detroitlions.com", "www.therams.com", "www.seahawks.com",
}

# Files this session is allowed to have changed, outside its own namespace.
ALLOWED_SHARED = {
    # deliberately edited by this session, each one logged as a change request in
    # COORDINATION.md: the coordination board, the readme, the landing-page prose, the
    # data dictionary, the site-tree map, and the three shared registers.
    "COORDINATION.md", "README.md", "EXECUTIVE_SUMMARY.md", "content/index.md",
    "content/data-dictionary.md",
    # data/s745_* are derived from data/suggestions.csv and data/questions.csv by
    # scripts/build_s745_decisions.py, so appending register rows regenerates them.
    "data/s745_suggestion_scores.csv", "data/s745_decision_paths.csv",
    "data/s745_information_gaps.csv", "tools/build_site.py",
    "data/flags.csv", "data/questions.csv", "data/suggestions.csv",
    # regenerated by tools/build_site.py as a consequence of the edits above
    "index.html", "404.html", "data-dictionary.html", "data/build_manifest.json",
}


class Auditor(html.parser.HTMLParser):
    def __init__(self, path):
        super().__init__()
        self.path = path
        self.local = []
        self.ext = []
        self.tables = []
        self._t = None
        self._thead = False
        self._tbody = False
        self._row = None

    def handle_starttag(self, tag, attrs):
        ad = dict(attrs)
        for attr in ("href", "src"):
            v = (ad.get(attr) or "").strip()
            if not v or v.startswith(("mailto:", "#", "javascript:", "data:", "tel:")):
                continue
            if v.startswith(("http://", "https://")):
                self.ext.append((self.getpos()[0], v))
                if self._row is not None:
                    self._row["links"].append(v)
            else:
                self.local.append((self.getpos()[0], v))
        if tag == "table":
            self._t = {"head": 0, "rows": []}
            self.tables.append(self._t)
        elif tag == "thead":
            self._thead = True
        elif tag == "tbody":
            self._tbody = True
        elif tag == "tr" and self._t is not None and self._tbody:
            self._row = {"cells": 0, "links": []}
            self._t["rows"].append(self._row)
        elif tag in ("th", "td"):
            span = int(ad.get("colspan", "1") or 1)
            if self._thead:
                self._t["head"] += span
            elif self._row is not None:
                self._row["cells"] += span

    def handle_endtag(self, tag):
        if tag == "thead":
            self._thead = False
        elif tag == "tbody":
            self._tbody = False
        elif tag == "table":
            self._t = None
        elif tag == "tr":
            self._row = None


def approved(url):
    try:
        host = url.split("//", 1)[1].split("/", 1)[0]
    except IndexError:
        return False
    return host in OFFICIAL_DOMAINS


def sha(path):
    return hashlib.sha256(pathlib.Path(path).read_bytes()).hexdigest()


def main():
    errors, checks = [], 0

    # build first, audit second: the audit must read what the committed data produces,
    # not whatever happened to be on disk from an earlier run.
    r = subprocess.run([sys.executable, "tools/s2268_build_site.py"], cwd=ROOT,
                       capture_output=True, text=True)
    checks_scope = 0
    if r.returncode != 0:
        errors.append(f"tools/s2268_build_site.py exited {r.returncode}: {r.stderr.strip()[:300]}")
    r = subprocess.run([sys.executable, "tools/build_site.py"], cwd=ROOT,
                       capture_output=True, text=True)
    if r.returncode != 0:
        errors.append(f"tools/build_site.py exited {r.returncode}: {r.stderr.strip()[:300]}")

    pages = sorted(OUT.glob("*.html"))
    if len(pages) != 11:
        errors.append(f"expected 11 pages in s2268/, found {len(pages)}")

    n_tables = n_rows = 0
    for page in pages:
        a = Auditor(page)
        a.feed(page.read_text())
        rel = page.relative_to(ROOT)

        for line, ref in a.local:
            checks += 1
            target = (page.parent / ref.split("#")[0]).resolve()
            if not target.exists():
                errors.append(f"{rel}:{line} broken local link -> {ref}")

        for t in a.tables:
            n_tables += 1
            for i, r in enumerate(t["rows"]):
                n_rows += 1
                checks += 1
                if t["head"] and r["cells"] != t["head"]:
                    errors.append(f"{rel}: table row {i} has {r['cells']} cells, header has {t['head']}")
                if not any(approved(u) for u in r["links"]):
                    errors.append(f"{rel}: table row {i} carries no official source link")

    # reproducibility: the CSVs must regenerate byte-identically
    tracked = sorted((ROOT / "data").glob("s2268_*.csv"))
    before = {p.name: sha(p) for p in tracked}
    for script in ("tools/s2268_competition.py", "tools/s2268_refresh.py"):
        r = subprocess.run([sys.executable, script], cwd=ROOT, capture_output=True, text=True)
        checks += 1
        if r.returncode != 0:
            errors.append(f"{script} exited {r.returncode}: {r.stderr.strip()[:300]}")
    after = {p.name: sha(p) for p in sorted((ROOT / "data").glob("s2268_*.csv"))}
    for name in before:
        checks += 1
        if before.get(name) != after.get(name):
            errors.append(f"{name} is not reproducible: it changed on regeneration")

    # the pages must be exactly what the data says
    r = subprocess.run([sys.executable, "tools/s2268_build_site.py"], cwd=ROOT,
                       capture_output=True, text=True)
    checks += 1
    if r.returncode != 0:
        errors.append(f"tools/s2268_build_site.py exited {r.returncode}: {r.stderr.strip()[:300]}")
    else:
        built = {p.name: sha(p) for p in sorted(OUT.glob("*.html"))}
        r2 = subprocess.run([sys.executable, "tools/s2268_build_site.py"], cwd=ROOT,
                            capture_output=True, text=True)
        rebuilt = {p.name: sha(p) for p in sorted(OUT.glob("*.html"))}
        for name in built:
            checks += 1
            if built[name] != rebuilt[name]:
                errors.append(f"{name} is not a deterministic build")

    # scope: nothing outside this session's namespace unless it was logged
    r = subprocess.run(["git", "-C", str(ROOT), "status", "--porcelain"],
                       capture_output=True, text=True)
    changed = [l[3:].strip().strip('"') for l in r.stdout.splitlines() if l.strip()]

    for c in changed:
        checks += 1
        if c.startswith("s2268/") or c.startswith("data/s2268_") or c.startswith("tools/s2268_"):
            continue
        # Root-level *.html is a build product of tools/build_site.py, which renders it from
        # content/ and data/; it is not an edit. The drift check in validate.yml is the guard
        # against a hand edit surviving.
        if "/" not in c and (c.endswith(".html") or c == "data/build_manifest.json"):
            continue
        if c in ALLOWED_SHARED:
            continue
        errors.append(f"file outside this session's scope was modified: {c}")

    suites = [
        ("tools/build_site.py", ["python3", "tools/build_site.py"]),
        ("tools/verify.py", ["python3", "tools/verify.py"]),
        ("tools/check_site.py", ["python3", "tools/check_site.py"]),
        ("scripts/audit_all_pages.py", ["python3", "scripts/audit_all_pages.py"]),
        ("scripts/verify_q51.py", ["python3", "scripts/verify_q51.py"]),
        ("scripts/verify_s53126614.py", ["python3", "scripts/verify_s53126614.py"]),
    ]
    print("=" * 78)
    for label, cmd in suites:
        r = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True)
        checks += 1
        tail = (r.stdout.strip().splitlines() or ["<no output>"])[-1]
        status = "PASS" if r.returncode == 0 else "FAIL"
        print(f"  {status}  {label:34s} {tail[:120]}")
        if r.returncode != 0:
            errors.append(f"{label} exited {r.returncode}: {tail[:300]}")

    print("=" * 78)
    print(f"s2268: {len(pages)} pages · {n_tables} tables · {n_rows} rows · "
          f"{len(tracked)} reproducible data files")
    if errors:
        print(f"\nFAILED with {len(errors)} error(s):")
        for e in errors:
            print("  -", e)
        return 1
    print(f"VERIFY PASSED: {checks} checks, 0 errors.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
